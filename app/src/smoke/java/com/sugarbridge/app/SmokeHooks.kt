/**
 * Only in the "smoke" build, which is optimized like a release: instrumented tests can't run against optimized
 * code, so tools/smoke_test.py drives this build from outside instead. A provider starts with the process, the
 * earliest place to put a stand-in for LibreLinkUp and GitHub, and also serves an export to open.
 */
class SmokeHooks : ContentProvider() {

    override fun onCreate(): Boolean {
        Libre.transportForTests = SmokeCloud
        Updater.transportForTests = HttpTransport { _, _, _, _ -> HttpResponse(404, "") }
        LibreViewActivity.pageForTests = libreViewPage()
        return true
    }

    /** content://com.sugarbridge.app.smoke/export.csv */
    override fun openFile(uri: Uri, mode: String): ParcelFileDescriptor {
        val file = File(context!!.cacheDir, "smoke-export.csv").apply { writeText(export()) }
        return ParcelFileDescriptor.open(file, ParcelFileDescriptor.MODE_READ_ONLY)
    }

    override fun getType(uri: Uri) = "text/csv"
    override fun query(uri: Uri, projection: Array<out String>?, selection: String?, args: Array<out String>?, order: String?): Cursor? = null
    override fun insert(uri: Uri, values: ContentValues?): Uri? = null
    override fun delete(uri: Uri, selection: String?, args: Array<out String>?) = 0
    override fun update(uri: Uri, values: ContentValues?, selection: String?, args: Array<out String>?) = 0

    /** Ten days of readings every 15 minutes, the way LibreView exports them. */
    private fun export(): String {
        val format = DateTimeFormatter.ofPattern("dd-MM-yyyy HH:mm")
        val zone = ZoneId.systemDefault()
        val now = Instant.now().epochSecond / 900 * 900
        val rows = (960 downTo 1).joinToString("") { i ->
            val time = Instant.ofEpochSecond(now - i * 900L).atZone(zone).format(format)
            "FreeStyle LibreLink,X,$time,0,${5 + (i % 40) / 10.0},\n"
        }
        return "Glucose Data,Generated on,today,Generated by,Smoke\n" +
            "Device,Serial Number,Device Timestamp,Record Type,Historic Glucose mmol/L,Scan Glucose mmol/L\n" + rows
    }

    /** A page that builds a file in the browser and offers it, which goes through the window's bridge. */
    private fun libreViewPage(): String {
        val csv = export().replace("\n", "\\n")
        return """
            <html><body><h2>LibreView (smoke)</h2><a id="d" download="glucose.csv">Download</a>
            <script>
              setTimeout(function () {
                var url = URL.createObjectURL(new Blob(["$csv"], {type: "text/csv"}));
                var a = document.getElementById("d");
                a.href = url;
                a.click();
                URL.revokeObjectURL(url);
              }, 3000);
            </script></body></html>
        """.trimIndent()
    }
}

/** A LibreLinkUp on the real clock: every minute brings a new current value. */
private object SmokeCloud : HttpTransport {
    override fun send(method: String, url: String, headers: Map<String, String>, body: String?): HttpResponse {
        val newest = Instant.ofEpochSecond(Instant.now().epochSecond / 60 * 60 - 30)
        val data: Any = when (URI(url).path) {
            "/llu/auth/login" -> JSONObject()
                .put("user", JSONObject().put("id", "smoke"))
                .put("authTicket", JSONObject().put("token", "SMOKE"))
            "/llu/connections" -> JSONArray().put(JSONObject().put("patientId", "p-1"))
            "/llu/connections/p-1/graph" -> JSONObject()
                .put("connection", JSONObject().put("glucoseMeasurement", item(newest).put("TrendArrow", 3)))
                .put("graphData", JSONArray().apply {
                    val quarter = newest.epochSecond / 900 * 900
                    (48 downTo 1).forEach { put(item(Instant.ofEpochSecond(quarter - it * 900L))) }
                })
            else -> return HttpResponse(404, "")
        }
        return HttpResponse(200, JSONObject().put("status", 0).put("data", data).toString())
    }

    private fun item(time: Instant) = JSONObject()
        .put("FactoryTimestamp", LocalDateTime.ofInstant(time, ZoneOffset.UTC).format(LIBRE_TIME))
        .put("ValueInMgPerDl", 100 + (time.epochSecond / 60 % 40))
}
