package com.sugarbridge.app

import android.content.Context
import android.os.SystemClock
import androidx.lifecycle.ViewModelProvider
import androidx.test.core.app.ActivityScenario
import androidx.test.ext.junit.runners.AndroidJUnit4
import androidx.test.platform.app.InstrumentationRegistry
import com.sugarbridge.app.libreview.HistoryStore
import com.sugarbridge.app.libreview.MergeMode
import com.sugarbridge.app.settings.SettingsStore
import org.junit.After
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Before
import org.junit.Test
import org.junit.runner.RunWith
import java.io.File
import java.time.ZoneId

/**
 * The loaded history stays until it is deleted: it is back after a restart (also from version 1.6's raw file),
 * a broken file is dropped quietly, and a new export is merged with it the way the user chooses.
 */
@RunWith(AndroidJUnit4::class)
class HistoryRestoreTest {

    private val context = InstrumentationRegistry.getInstrumentation().targetContext

    private fun csv(vararg rows: String) =
        "Glucose Data,Generated on,08-10-2026 18:30 UTC,Generated by,Test\n" +
            "Device,Serial Number,Device Timestamp,Record Type,Historic Glucose mmol/L,Scan Glucose mmol/L\n" +
            rows.joinToString("") { "FreeStyle LibreLink,X,$it\n" }

    private val first = csv("08-10-2026 17:47,0,6.4,", "08-10-2026 18:02,0,6.9,", "08-10-2026 18:05,1,,7.1")
    // a later export: 18:02 again with another value, 18:17 and 18:32 new; 17:47 and the scan are no longer in it
    private val second = csv("08-10-2026 18:02,0,7.5,", "08-10-2026 18:17,0,8.0,", "08-10-2026 18:32,0,8.4,")

    @Before
    fun setUp() {
        SettingsStore(context).languageChosen = true
        HistoryStore.clear(context)
    }

    @After
    fun cleanUp() = HistoryStore.clear(context)

    private fun <T> withViewModel(block: (ActivityScenario<MainActivity>, MainViewModel) -> T): T =
        ActivityScenario.launch(MainActivity::class.java).use { scenario ->
            lateinit var vm: MainViewModel
            scenario.onActivity { vm = ViewModelProvider(it)[MainViewModel::class.java] }
            block(scenario, vm)
        }

    private fun waitFor(timeoutMs: Long = 10_000, condition: () -> Boolean): Boolean {
        val deadline = SystemClock.uptimeMillis() + timeoutMs
        while (SystemClock.uptimeMillis() < deadline) {
            if (condition()) return true
            Thread.sleep(100)
        }
        return condition()
    }

    private fun export(text: String): String = File(context.cacheDir, "export.csv").apply { writeText(text) }.absolutePath

    @Test
    fun aHistoryFromVersion16IsReadAndKeptInTheNewFormat() {
        HistoryStore.legacyFile(context).writeText(first)
        context.getSharedPreferences("history", Context.MODE_PRIVATE).edit().putString("source", "LibreView").commit()
        withViewModel { _, vm ->
            assertTrue("the history didn't come back", waitFor { vm.history.loaded })
            assertEquals(3, vm.history.readings.size)
            assertEquals("LibreView", vm.history.source)
            assertFalse("a restored history waits on the start page", vm.historyOpen)
        }
        assertFalse(HistoryStore.legacyFile(context).exists())
        assertEquals(3, HistoryStore.load(context, ZoneId.systemDefault())!!.readings.size)
    }

    @Test
    fun deletingForgetsTheHistoryForGood() {
        withViewModel { scenario, vm ->
            scenario.onActivity { vm.importFile(export(first)) }
            assertTrue(waitFor { vm.history.loaded && vm.historyOpen })
            assertTrue(waitFor { HistoryStore.exists(context) })
            scenario.onActivity { vm.deleteHistory() }
            assertFalse(vm.history.loaded)
        }
        assertTrue(waitFor { !HistoryStore.exists(context) })
        withViewModel { _, vm ->
            Thread.sleep(1500)
            assertFalse(vm.history.loaded)
        }
    }

    @Test
    fun aBrokenFileIsDroppedQuietly() {
        File(context.filesDir, "history.txt").writeText("sugarbridge-history 1\tMMOL\t1\tx\nnot,a,number\n")
        withViewModel { _, vm ->
            assertTrue("the broken file was kept", waitFor { !HistoryStore.exists(context) })
            assertFalse(vm.history.loaded)
        }
    }

    @Test
    fun aNewExportIsComparedAndMergedAsChosen() {
        withViewModel { scenario, vm ->
            scenario.onActivity { vm.importFile(export(first)) }
            assertTrue(waitFor { vm.history.loaded })

            // add: the loaded values stay, the new readings come on top
            scenario.onActivity { vm.importFile(export(second)) }
            assertTrue(waitFor { vm.pendingMerge != null })
            val plan = vm.pendingMerge!!.plan
            assertEquals(listOf(3, 2, 0, 1, 2), listOf(plan.incoming, plan.added, plan.same, plan.changed, plan.onlyOld))
            scenario.onActivity { vm.applyMerge(MergeMode.ADD) }
            assertTrue(waitFor { vm.history.readings.size == 5 })
            assertNull(vm.pendingMerge)
            assertEquals(6.9, valueAt(vm, "18:02"), 0.0)

            // overwrite: the differing reading takes the new value
            scenario.onActivity { vm.importFile(export(second)) }
            assertTrue(waitFor { vm.pendingMerge != null })
            scenario.onActivity { vm.applyMerge(MergeMode.OVERWRITE) }
            assertTrue(waitFor { vm.pendingMerge == null && valueAt(vm, "18:02") == 7.5 })
            assertEquals(5, vm.history.readings.size)

            // replace: only the new export is left
            scenario.onActivity { vm.importFile(export(second)) }
            assertTrue(waitFor { vm.pendingMerge != null })
            scenario.onActivity { vm.applyMerge(MergeMode.REPLACE) }
            assertTrue(waitFor { vm.history.readings.size == 3 })
        }
        // what is shown is what is kept
        assertNotNull(HistoryStore.load(context, ZoneId.systemDefault()))
        assertEquals(3, HistoryStore.load(context, ZoneId.systemDefault())!!.readings.size)
    }

    /** The automatic reading at that clock time of the export (exports carry the phone's local time). */
    private fun valueAt(vm: MainViewModel, clock: String): Double =
        vm.history.readings.single { !it.scan && it.time.atZone(ZoneId.systemDefault()).toLocalTime().toString() == clock }.mmol
}
