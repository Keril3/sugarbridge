/**
 * The LibreView window catches a CSV the site builds right in the browser (blob:) and revokes at once.
 * The real LibreView needs a sign-in and a captcha, so the window gets a test page at a libreview.com address.
 */
@RunWith(AndroidJUnit4::class)
class LibreViewDownloadTest {

    @get:Rule
    // v1 on purpose: the v2 rule holds coroutines back until the test clock moves; these tests check what shows at once
    @Suppress("DEPRECATION")
    val compose = createEmptyComposeRule()

    private val instrumentation = InstrumentationRegistry.getInstrumentation()
    private val context = instrumentation.targetContext

    @After
    fun forgetThePage() {
        LibreViewActivity.pageForTests = null
    }

    private val page = """
        <html><body style="font-family:sans-serif;padding:24px">
        <h2>LibreView (test page)</h2><a id="d" download="glucose.csv">Download</a>
        <script>
          var csv = "Glucose Data,Generated on,08-10-2026 18:30 UTC,Generated by,Test\n" +
            "Device,Serial Number,Device Timestamp,Record Type,Historic Glucose mmol/L,Scan Glucose mmol/L\n" +
            "FreeStyle LibreLink,X,08-10-2026 17:47,0,6.4,\n" +
            "FreeStyle LibreLink,X,08-10-2026 18:02,0,6.9,\n" +
            "FreeStyle LibreLink,X,08-10-2026 18:05,1,,7.1\n";
          setTimeout(function () {
            var url = URL.createObjectURL(new Blob([csv], {type: "text/csv"}));
            var a = document.getElementById("d");
            a.href = url;
            a.click();
            URL.revokeObjectURL(url);   // like many sites do: right after the click
          }, 5000);
        </script></body></html>
    """.trimIndent()

    @Test
    fun blobDownloadIsCaptured() {
        val result = File(context.cacheDir, "libreview.csv").apply { delete() }
        LibreViewActivity.pageForTests = page
        context.startActivity(Intent(context, LibreViewActivity::class.java).addFlags(Intent.FLAG_ACTIVITY_NEW_TASK))
        Thread.sleep(1500)
        shot("libreview_1")
        Thread.sleep(2000)
        shot("libreview_2")

        val deadline = SystemClock.uptimeMillis() + 30_000
        while (!result.exists() && SystemClock.uptimeMillis() < deadline) Thread.sleep(200)
        assertTrue("the LibreView file was not caught", result.exists())
        val parsed = LibreViewCsv.parse(LibreViewCsv.decode(result.readBytes()))
        assertEquals(3, parsed.readings.size)
        assertEquals(6.4, parsed.readings.first().mmol, 0.0)
    }

    /**
     * The site must get nearly the whole screen, and the page must see that height too:
     * LibreView sizes itself with "height: 100%", which was 0 and left the sign-in in a 50 px box.
     */
    @Test
    fun siteFillsTheScreen() {
        val html = """<html><body style="margin:0"><div id="full" style="height:100vh">LibreView</div></body></html>"""
        LibreViewActivity.pageForTests = html
        ActivityScenario.launch(LibreViewActivity::class.java).use { scenario ->
            Thread.sleep(1500)
            lateinit var web: WebView
            scenario.onActivity { activity ->
                val root = activity.window.decorView
                web = findWebView(root)!!
                val share = web.height.toFloat() / root.height
                assertTrue("the site gets only ${(share * 100).toInt()}% of the screen", share > 0.8f)
            }
            val heights = LinkedBlockingQueue<String>()
            scenario.onActivity {
                web.evaluateJavascript("[document.getElementById('full').offsetHeight, document.documentElement.clientHeight, innerHeight].join(',')") {
                    heights.add(it.trim('"'))
                }
            }
            val (vh, html100, inner) = heights.poll(10, TimeUnit.SECONDS)!!.split(',').map { it.toInt() }
            assertTrue("100vh is $vh px, the window is $inner px", vh > inner * 0.9)
            assertTrue("height: 100% is $html100 px, the window is $inner px", html100 > inner * 0.9)
        }
    }

    /** A large phone font must not enlarge the site's text: LibreView's cards have a fixed width. */
    @Test
    fun largePhoneFontKeepsSiteTextSize() {
        val shell = instrumentation.uiAutomation
        shell.executeShellCommand("settings put system font_scale 1.3").close()
        try {
            Thread.sleep(1000)
            val html = """<html><body style="font-size:16px">LibreView</body></html>"""
            LibreViewActivity.pageForTests = html
            ActivityScenario.launch(LibreViewActivity::class.java).use { scenario ->
                Thread.sleep(1500)
                val size = LinkedBlockingQueue<String>()
                scenario.onActivity { activity ->
                    findWebView(activity.window.decorView)!!.evaluateJavascript("getComputedStyle(document.body).fontSize") { size.add(it.trim('"')) }
                }
                assertEquals("16px", size.poll(10, TimeUnit.SECONDS))
            }
        } finally {
            shell.executeShellCommand("settings put system font_scale 1.0").close()
        }
    }

    private fun findWebView(view: View): WebView? = when (view) {
        is WebView -> view
        is ViewGroup -> (0 until view.childCount).firstNotNullOfOrNull { findWebView(view.getChildAt(it)) }
        else -> null
    }

    /** The real site in the window: a visual check that it opens in the embedded browser. */
    @Test
    fun realSiteOpens() {
        context.startActivity(Intent(context, LibreViewActivity::class.java).addFlags(Intent.FLAG_ACTIVITY_NEW_TASK))
        Thread.sleep(12_000)
        shot("libreview_real")
        instrumentation.uiAutomation.executeShellCommand("input keyevent KEYCODE_BACK").close()
        Thread.sleep(500)
        instrumentation.uiAutomation.executeShellCommand("input keyevent KEYCODE_HOME").close()
    }

    private fun shot(name: String) {
        val bitmap = instrumentation.uiAutomation.takeScreenshot()
        val dir = File(context.filesDir, "shots").apply { mkdirs() }
        File(dir, "$name.png").outputStream().use { bitmap.compress(Bitmap.CompressFormat.PNG, 100, it) }
    }

    /** No file comes through from a page of another site, and the title says whose page it is. */
    @Test
    fun anotherSitesPageOffersNoFileAndIsNamed() {
        val result = File(context.cacheDir, "libreview.csv").apply { delete() }
        LibreViewActivity.pageForTests = "<html><body>LibreView</body></html>"
        ActivityScenario.launch(LibreViewActivity::class.java).use { scenario ->
            Thread.sleep(1500)
            scenario.onActivity { activity ->
                findWebView(activity.window.decorView)!!.loadDataWithBaseURL("https://example.com/", page, "text/html", "utf-8", null)
            }
            compose.waitUntil(10_000) { runCatching { compose.onNodeWithText("example.com").assertExists() }.isSuccess }
            Thread.sleep(7_000)   // the page clicks its download link after 5 seconds
            assertFalse("a file came from example.com", result.exists())
        }
    }

    /** A script that doesn't know the token, as in a frame of another site, gets nothing through the bridge. */
    @Test
    fun theBridgeTakesNothingWithoutItsToken() {
        val result = File(context.cacheDir, "libreview.csv").apply { delete() }
        val csv = android.util.Base64.encodeToString(
            ("Device,Serial Number,Device Timestamp,Record Type,Historic Glucose mmol/L,Scan Glucose mmol/L\n" +
                "FreeStyle LibreLink,X,08-10-2026 17:47,0,6.4,\n").toByteArray(),
            android.util.Base64.NO_WRAP,
        )
        LibreViewActivity.pageForTests = "<html><script>SugarBridgeCsv.onData('wrong', 'data:text/csv;base64,$csv');</script></html>"
        ActivityScenario.launch(LibreViewActivity::class.java).use {
            Thread.sleep(3_000)
            assertFalse("the bridge took a file without the token", result.exists())
        }
    }

    /** A broken data: link is reported, as it used to crash the app. */
    @Test
    fun aBrokenDataLinkDoesNotCrash() {
        LibreViewActivity.pageForTests = "<html><body><a id='d' href='data:text/csv,100%'>x</a><script>document.getElementById('d').click()</script></body></html>"
        ActivityScenario.launch(LibreViewActivity::class.java).use { scenario ->
            Thread.sleep(3_000)
            scenario.onActivity { assertFalse(it.isFinishing) }
        }
    }

    /** Signing out of SugarBridge signs out of LibreView's window too. */
    @Test
    fun signingOutForgetsTheSite() {
        instrumentation.runOnMainSync {
            CookieManager.getInstance().setCookie("https://www.libreview.com/", "session=1")
            CookieManager.getInstance().flush()
        }
        assertTrue("WebView keeps its data elsewhere", File(context.dataDir, "app_webview").exists())
        var cookie: String? = null
        instrumentation.runOnMainSync { cookie = CookieManager.getInstance().getCookie("https://www.libreview.com/") }
        assertNotNull(cookie)
        instrumentation.runOnMainSync { LibreViewActivity.forgetSession(context) }
        val deadline = SystemClock.uptimeMillis() + 5_000
        while (cookie != null && SystemClock.uptimeMillis() < deadline) {
            Thread.sleep(100)
            instrumentation.runOnMainSync { cookie = CookieManager.getInstance().getCookie("https://www.libreview.com/") }
        }
        assertNull(cookie)
    }
}
