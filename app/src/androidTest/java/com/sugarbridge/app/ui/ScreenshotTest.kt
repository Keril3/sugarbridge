/**
 * Walks through the screens with demo data in English and in Russian and saves screenshots to the app's
 * files/shots/<language>. Get one with: adb exec-out run-as com.sugarbridge.app cat files/shots/en/home.png > home.png
 */
@RunWith(AndroidJUnit4::class)
class ScreenshotTest {

    @get:Rule
    val compose = createEmptyComposeRule()

    private val instrumentation = InstrumentationRegistry.getInstrumentation()
    private val context = instrumentation.targetContext
    private val zone = ZoneId.systemDefault()
    private val today = LocalDate.now(zone)
    private val firstDay = today.minusDays(20)

    /** A plausible day: flat at night, rises after meals. */
    private fun mgDlAt(t: Instant): Double {
        val local = t.atZone(zone)
        val h = local.hour + local.minute / 60.0
        val meals = listOf(8.0, 13.5, 19.5).sumOf { m -> 75 * exp(-((h - m - 1.2) * (h - m - 1.2)) / 1.1) }
        return 98 + 10 * sin(h / 2.5 + local.dayOfYear) + meals
    }

    private fun day(date: LocalDate): List<Reading> =
        (0 until 96).map { i -> date.atStartOfDay(zone).plusMinutes(15L * i).toInstant() }
            .filter { it.isBefore(Instant.now()) }
            .map { Reading(it, Math.round(mgDlAt(it) * 10) / 10.0, 0) }

    private fun demoCsv(): String {
        val format = DateTimeFormatter.ofPattern("dd-MM-yyyy HH:mm")
        val rows = generateSequence(firstDay) { it.plusDays(1) }.takeWhile { !it.isAfter(today) }
            .flatMap { day(it) }
            .map { r ->
                val time = r.time.atZone(zone).format(format)
                "FreeStyle LibreLink,ABCD-1234,$time,0,${String.format(Locale.US, "%.1f", r.mmol)},,,,,,,,,,,,,,"
            }
        return (sequenceOf(
            "Glucose Data,Generated on,${today.format(DateTimeFormatter.ofPattern("dd-MM-yyyy"))} 12:00 UTC,Generated by,Tenshi",
            "Device,Serial Number,Device Timestamp,Record Type,Historic Glucose mmol/L,Scan Glucose mmol/L," +
                "Non-numeric Rapid-Acting Insulin,Rapid-Acting Insulin (units),Non-numeric Food,Carbohydrates (grams)," +
                "Carbohydrates (servings),Non-numeric Long-Acting Insulin,Long-Acting Insulin (units),Notes," +
                "Strip Glucose mmol/L,Ketone mmol/L,Meal Insulin (units),Correction Insulin (units),User Change Insulin (units)",
        ) + rows).joinToString("\n")
    }

    @Before
    fun seed() {
        // background sync is off: with the demo account LibreLinkUp would answer "wrong password"
        // no check for updates by itself: a newer version on GitHub would cover the screens with its offer
        SettingsStore(context).save(AppSettings(backgroundMinutes = 0, liveEnabled = false, autoUpdateCheck = false))
        HistoryStore.clear(context)   // a history kept from another run would replace the empty History tab
        SettingsStore(context).languageChosen = true
        AccountStore(context).save(Account("tenshi@example.com", "demo", Session("ru", "demo-token", sha256("demo"))))
        val now = Instant.now()
        val recent = (48 downTo 1).map { now.minusSeconds(it * 900L) }.map { Reading(it, Math.round(mgDlAt(it) * 10) / 10.0, 0) } +
            Reading(now.minusSeconds(40), mgDlAt(now), 4)
        SyncStore(context).saveSuccess(recent, 3)   // "the last sync was just now": no automatic sync
        if (healthConnectState(context) == HealthConnectState.AVAILABLE) {
            instrumentation.uiAutomation.grantRuntimePermission(context.packageName, WRITE_GLUCOSE)
            // two weeks are already "in Health Connect": those days get a mark in the history,
            // and the home screen gets the estimated HbA1c for 14 days
            runBlocking { insertReadings(context, (0L..13L).flatMap { day(today.minusDays(it)) }) }
        }
    }

    @After
    fun cleanUp() {
        runBlocking {
            runCatching { deleteOwnGlucose(context, firstDay.atStartOfDay(zone).toInstant(), Instant.now().plusSeconds(3600)) }
        }
        instrumentation.uiAutomation.executeShellCommand("cmd uimode night no").close()
        useAppLanguage(context, null)
        Libre.signOut(context)
        SyncStore(context).clearDisplay()
        Updater.transportForTests = null
        context.getSharedPreferences("update", Context.MODE_PRIVATE).edit().clear().commit()
    }

    private fun shot(language: String, name: String) {
        compose.waitForIdle()
        Thread.sleep(700)
        val bitmap = instrumentation.uiAutomation.takeScreenshot()
        val dir = File(context.filesDir, "shots/$language").apply { mkdirs() }
        File(dir, "$name.png").outputStream().use { bitmap.compress(Bitmap.CompressFormat.PNG, 100, it) }
    }

    @Test
    fun englishScreens() = allScreens("en")

    @Test
    fun russianScreens() = allScreens("ru")

    private fun allScreens(language: String) {
        useAppLanguage(context, language)
        val res = resourcesIn(context, language)
        fun text(id: Int) = res.getString(id)

        val scenario = ActivityScenario.launch(MainActivity::class.java)
        lateinit var vm: MainViewModel
        scenario.onActivity { vm = ViewModelProvider(it)[MainViewModel::class.java] }

        compose.waitUntil(10_000) { vm.ui.signedIn && vm.ui.canWrite != null }
        compose.onNodeWithText(text(R.string.tab_now)).assertExists()   // the screen really is in this language
        shot(language, "home")
        scenario.onActivity { vm.notify(R.string.msg_nothing_new) }   // what "Sync now" says: a small window of its own
        compose.onNodeWithTag("popup").assertExists()
        shot(language, "popup")
        compose.onNodeWithTag("popup").performClick()   // a tap closes it
        compose.waitUntil(5_000) { compose.onAllNodesWithTag("popup").fetchSemanticsNodes().isEmpty() }
        compose.onNodeWithTag("mascot").performClick()   // she tilts her head, closes her eyes and smiles
        shot(language, "home_tap")
        compose.waitUntil(20_000) { vm.ui.gmi14 != null }
        compose.onNodeWithText(res.getString(R.string.gmi_hint, 70)).performScrollTo()
        shot(language, "home_gmi")

        // the chart opens full screen; a finger dragged along it picks a point
        compose.onNodeWithText(text(R.string.chart_hint)).performScrollTo().performClick()
        compose.onNodeWithTag("chart-full").performTouchInput {
            down(Offset(width * 0.3f, height * 0.5f))
            moveTo(Offset(width * 0.55f, height * 0.5f))
            up()
        }
        shot(language, "chart")
        Espresso.pressBack()

        compose.onNodeWithText(text(R.string.tab_history)).performClick()
        shot(language, "history_empty")

        val file = File(context.cacheDir, "demo.csv").apply { writeText(demoCsv()) }
        scenario.onActivity { vm.importFile(file.absolutePath) }
        compose.waitUntil(20_000) { vm.history.loaded && !vm.history.busy }
        shot(language, "history")

        // the history chart opens full screen; a finger picks a point with its date
        compose.onNodeWithTag("history-chart").performClick()
        compose.onNodeWithTag("chart-full").performTouchInput {
            down(Offset(width * 0.5f, height * 0.5f))
            up()
        }
        shot(language, "history_chart")
        Espresso.pressBack()
        // the days' heading and its quick choices stand on a glass bar, readable on the sky by day and by night
        compose.onNode(hasScrollToNodeAction()).performScrollToNode(hasTestTag("days-header"))   // further down the list
        shot(language, "history_days")
        compose.onNodeWithTag("select-all").performClick()
        compose.waitUntil(5_000) { vm.history.selected.isNotEmpty() }
        compose.onNodeWithTag("select-none").performClick()
        compose.waitUntil(5_000) { vm.history.selected.isEmpty() }
        scenario.onActivity { vm.updateSettings { it.copy(theme = ThemeMode.DARK) } }
        shot(language, "history_days_night")
        scenario.onActivity { vm.updateSettings { it.copy(theme = ThemeMode.LIGHT) } }
        // the days to write are picked in the calendar
        // the bar with the write button lies over the end of the list: press the button itself, not the screen there
        compose.onNodeWithTag("sync-period").performScrollTo().performSemanticsAction(SemanticsActions.OnClick)
        compose.onNodeWithTag("calendar-title").assertExists()
        shot(language, "calendar")
        compose.onNodeWithTag("calendar-title").performClick()   // the grid of months
        shot(language, "calendar_months")
        compose.onNodeWithText(text(R.string.cancel)).performClick()

        // "Back" leads to the History start page, where the loaded history is one tap away
        Espresso.pressBack()
        compose.onNodeWithTag("view-loaded").assertExists()
        shot(language, "history_start")
        // a new export over the loaded history asks how to combine them
        scenario.onActivity { vm.importFile(File(context.cacheDir, "demo.csv").apply { writeText(demoCsv()) }.absolutePath) }
        compose.waitUntil(20_000) { vm.pendingMerge != null }
        compose.onNodeWithTag("merge-add").assertExists()
        shot(language, "merge")
        compose.onNodeWithTag("merge-add").performClick()
        compose.waitUntil(20_000) { vm.pendingMerge == null && vm.historyOpen }

        compose.onNodeWithText(text(R.string.tab_settings)).performClick()
        shot(language, "settings")
        compose.onNodeWithText(text(R.string.settings_background_intro)).performScrollTo()
        shot(language, "settings_sync")
        compose.onNodeWithText(text(R.string.settings_about_title)).performScrollTo()
        shot(language, "settings_bottom")
        compose.onNodeWithTag("feedback").performScrollTo()
        shot(language, "settings_feedback")

        // minute mode turned background sync off: the notice stays until its link or its ✕ is tapped
        scenario.onActivity { vm.updateSettings { it.copy(backgroundNotice = true) } }
        compose.onNodeWithTag("background-notice").assertExists()
        shot(language, "background_notice")
        compose.onNodeWithTag("window-close").performClick()
        compose.waitUntil(5_000) { !vm.ui.settings.backgroundNotice }
        compose.onNodeWithTag("background-notice").assertDoesNotExist()
        scenario.onActivity { vm.updateSettings { it.copy(backgroundNotice = true) } }
        compose.onNodeWithTag("background-notice-link").performClick()
        compose.waitUntil(5_000) { !vm.ui.settings.backgroundNotice }
        compose.onNodeWithTag("background-notice").assertDoesNotExist()
        compose.waitUntil(5_000) { runCatching { compose.onNodeWithText(text(R.string.settings_background_intro)).assertIsDisplayed() }.isSuccess }

        // the developer tools
        scenario.onActivity { vm.updateSettings { it.copy(developer = true) } }
        // a message popping up at the bottom may cover the button for a moment: press the button itself
        compose.onNodeWithText(text(R.string.settings_developer_open)).performScrollTo().performSemanticsAction(SemanticsActions.OnClick)
        compose.waitUntil(15_000) { compose.onAllNodesWithText(text(R.string.dev_version)).fetchSemanticsNodes().isNotEmpty() }
        shot(language, "developer")
        Espresso.pressBack()
        scenario.onActivity { vm.updateSettings { it.copy(developer = false) } }

        // the target range is typed in: a new lower bound with the decimal separator of the language, then Save
        val locale = Locale.forLanguageTag(language)
        compose.onNode(hasSetTextAction() and hasText(formatGlucose(70.0, GlucoseUnit.MMOL, locale))).performTextReplacement(String.format(locale, "%.1f", 4.2))
        compose.onNodeWithText(text(R.string.target_save)).performClick()
        compose.waitUntil(5_000) { abs(vm.ui.settings.lowMgDl - 4.2 * MGDL_PER_MMOL) < 0.1 }
        scenario.onActivity { vm.updateSettings { it.copy(lowMgDl = 70.0) } }

        compose.onNodeWithText(text(R.string.tab_now)).performClick()
        scenario.onActivity { vm.updateSettings { it.copy(theme = ThemeMode.DARK) } }   // the sun/moon switch
        shot(language, "home_night")
        compose.onNodeWithText(text(R.string.tab_settings)).performClick()
        shot(language, "settings_night")
        scenario.onActivity { vm.updateSettings { it.copy(theme = ThemeMode.LIGHT) } }
        compose.onNodeWithText(text(R.string.tab_now)).performClick()

        // low vision: the plain font, larger, with more contrast, here also with the largest text
        scenario.onActivity { vm.updateSettings { it.copy(lowVision = true, textScale = 1.3f) } }
        shot(language, "home_low_vision")
        compose.onNodeWithText(text(R.string.tab_settings)).performClick()
        shot(language, "settings_low_vision")
        scenario.onActivity { vm.updateSettings { it.copy(lowVision = false, textScale = 1f) } }
        compose.onNodeWithText(text(R.string.tab_now)).performClick()

        // from the 12-hour chart straight to the loaded history
        compose.onNodeWithTag("all-history").performScrollTo().performSemanticsAction(SemanticsActions.OnClick)
        compose.waitUntil(5_000) { vm.historyOpen }
        compose.onNodeWithTag("history-chart").assertExists()
        compose.onNodeWithText(text(R.string.tab_now)).performClick()

        scenario.onActivity { ViewModelProvider(it)[MainViewModel::class.java].signOut() }
        SettingsStore(context).languageChosen = false   // the very first start: the language screen
        compose.waitUntil(5_000) { !vm.ui.signedIn && !vm.ui.languageChosen }
        compose.onNodeWithText(text(R.string.language_title)).assertExists()
        shot(language, "language")
        SettingsStore(context).languageChosen = true
        compose.waitUntil(5_000) { vm.ui.languageChosen }
        compose.onNodeWithText(text(R.string.login_title)).assertExists()
        shot(language, "login")

        // a new version is out (GitHub is a stand-in here): the check by itself offers it in a window, once
        context.getSharedPreferences("update", Context.MODE_PRIVATE).edit().clear().commit()
        Updater.transportForTests = HttpTransport { _, _, _, _ ->
            HttpResponse(
                200,
                """{"tag_name": "v99.0.0", "html_url": "$GITHUB_PAGE", "assets": [{"name": "$APK_NAME",
                   "browser_download_url": "https://github.com/$GITHUB_REPO/releases/download/v99.0.0/$APK_NAME"}]}""",
            )
        }
        scenario.onActivity { vm.updateSettings { it.copy(autoUpdateCheck = true) } }
        compose.waitUntil(10_000) { vm.updateOffer != null }
        compose.onNodeWithTag("update-offer").assertExists()
        shot(language, "update_offer")
        compose.onNodeWithText(text(R.string.update_later)).performClick()
        compose.waitUntil(5_000) { vm.updateOffer == null }
        assertTrue("offered again", !UpdateOffer.shouldOffer(context, vm.ui.settings, Updater.known(context)!!))
        scenario.close()
    }
}
