package com.sugarbridge.app.libreview

import com.sugarbridge.app.glucose.GlucoseUnit
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Test
import java.nio.charset.Charset
import java.time.Instant
import java.time.ZoneId

class LibreViewCsvTest {

    private val kaliningrad = ZoneId.of("Europe/Kaliningrad")   // UTC+2 круглый год

    private val header = "Device,Serial Number,Device Timestamp,Record Type,Historic Glucose mmol/L,Scan Glucose mmol/L," +
        "Non-numeric Rapid-Acting Insulin,Rapid-Acting Insulin (units),Non-numeric Food,Carbohydrates (grams)," +
        "Carbohydrates (servings),Non-numeric Long-Acting Insulin,Long-Acting Insulin (units),Notes,Strip Glucose mmol/L," +
        "Ketone mmol/L,Meal Insulin (units),Correction Insulin (units),User Change Insulin (units)"

    /** Строка данных: 19 колонок, как в настоящей выгрузке. */
    private fun row(time: String, type: Int, historic: String = "", scan: String = "", notes: String = "", carbs: String = ""): String {
        val cells = MutableList(19) { "" }
        cells[0] = "FreeStyle LibreLink"
        cells[1] = "ABCD-1234"
        cells[2] = time
        cells[3] = type.toString()
        cells[4] = historic
        cells[5] = scan
        cells[9] = carbs
        cells[13] = notes
        return cells.joinToString(",")
    }

    private fun csv(vararg rows: String) =
        (listOf("Glucose Data,Generated on,08-10-2026 18:30 UTC,Generated by,Test User", header) + rows).joinToString("\r\n")

    @Test
    fun europeanFileWithMmolIsParsed() {
        val result = LibreViewCsv.parse(
            csv(
                row("08-10-2026 17:47", 0, historic = "6.4"),
                row("08-10-2026 18:02", 0, historic = "6.9"),
                row("08-10-2026 18:05", 1, scan = "7.1"),
                row("08-10-2026 18:10", 5, carbs = "20", notes = "\"обед, суп\""),   // еда — не глюкоза
            ),
            kaliningrad,
        )
        assertEquals(GlucoseUnit.MMOL, result.unit)
        assertEquals(3, result.glucoseRows)
        assertEquals(0, result.skippedRows)
        assertEquals(listOf(115.3, 124.3, 127.9), result.readings.map { it.mgDl })   // 6,4 × 18,016 = 115,3
        assertEquals(Instant.parse("2026-10-08T15:47:00Z"), result.readings.first().time)   // местное время → UTC
        assertEquals(listOf(false, false, true), result.readings.map { it.scan })
        assertEquals(6.4, result.readings.first().mmol, 0.0)
    }

    @Test
    fun usFileWithMgDlAnd12HourClockIsParsed() {
        val text = listOf(
            "Glucose Data,Generated on,10-13-2026 06:30 PM UTC,Generated by,Test User",
            header.replace("mmol/L", "mg/dL"),
            row("10-08-2026 05:47 PM", 0, historic = "115"),
            row("10-09-2026 12:02 AM", 0, historic = "98"),   // 12 AM — это полночь
            row("10-13-2026 09:15 AM", 1, scan = "140"),      // 13 — день, значит формат месяц-день
        ).joinToString("\n")
        val result = LibreViewCsv.parse(text, kaliningrad)
        assertEquals(GlucoseUnit.MGDL, result.unit)
        assertEquals(listOf(115.0, 98.0, 140.0), result.readings.map { it.mgDl })
        assertEquals(
            listOf("2026-10-08T15:47:00Z", "2026-10-08T22:02:00Z", "2026-10-13T07:15:00Z").map(Instant::parse),
            result.readings.map { it.time },
        )
    }

    @Test
    fun russianFileWithSemicolonsAndDecimalCommasIsParsed() {
        val text = listOf(
            "Данные о глюкозе;Создано;08.10.2026 18:30 UTC;Создал;Тест",
            "Устройство;Серийный номер;Отметка времени устройства;Тип записи;Хронология уровня глюкозы ммоль/л;Сканирование уровня глюкозы ммоль/л;Заметки",
            "FreeStyle LibreLink;ABCD;08.10.2026 17:47;0;6,4;;",
            "FreeStyle LibreLink;ABCD;08.10.2026 18:02;0;\"6,9\";;",
            "FreeStyle LibreLink;ABCD;14.10.2026 07:00;1;;5,0;утро",
        ).joinToString("\n")
        val result = LibreViewCsv.parse(text, kaliningrad)
        assertEquals(GlucoseUnit.MMOL, result.unit)
        assertEquals(listOf(6.4, 6.9, 5.0), result.readings.map { it.mmol })
        assertEquals(Instant.parse("2026-10-14T05:00:00Z"), result.readings.last().time)
        assertTrue(result.readings.last().scan)
    }

    @Test
    fun quotedDecimalCommaInCommaSeparatedFile() {
        val result = LibreViewCsv.parse(csv(row("08-10-2026 17:47", 0, historic = "\"6,4\"")), kaliningrad)
        assertEquals(6.4, result.readings.single().mmol, 0.0)
    }

    @Test
    fun ambiguousDatesAreReadDayFirst() {
        // все дни ≤ 12: и 05-10, и 10-05 возможны; европейский порядок выигрывает
        val result = LibreViewCsv.parse(csv(row("05-10-2026 10:00", 0, historic = "6.0")), kaliningrad)
        assertEquals(Instant.parse("2026-10-05T08:00:00Z"), result.readings.single().time)
    }

    @Test
    fun notesWithLineBreaksDoNotBreakRows() {
        val result = LibreViewCsv.parse(
            csv(
                row("08-10-2026 18:10", 6, notes = "\"первая строка\nвторая, с запятой и \"\"кавычками\"\"\""),
                row("08-10-2026 18:15", 0, historic = "7.0"),
            ),
            kaliningrad,
        )
        assertEquals(listOf(7.0), result.readings.map { it.mmol })
    }

    @Test
    fun byteOrderMarkAndExtraHeaderLinesAreSkipped() {
        // выгрузка из кабинета врача: две строки с данными пациента перед заголовком
        val text = "\uFEFFPatient report\nName,Date of Birth,Report Date\nTest User,01-01-1990,08-10-2026\n" +
            header + "\n" + row("08-10-2026 17:47", 0, historic = "6.4")
        val result = LibreViewCsv.parse(text, kaliningrad)
        assertEquals(1, result.readings.size)
        assertEquals(0, result.skippedRows)
    }

    @Test
    fun unreadableValuesAreCountedAsSkipped() {
        val result = LibreViewCsv.parse(
            csv(
                row("08-10-2026 17:47", 0, historic = "HI"),
                row("08-10-2026 18:02", 0, historic = "LO"),
                row("не дата", 0, historic = "6.0"),
                row("08-10-2026 18:17", 0, historic = "6.1"),
            ),
            kaliningrad,
        )
        assertEquals(4, result.glucoseRows)
        assertEquals(3, result.skippedRows)
        assertEquals(1, result.readings.size)
    }

    @Test
    fun historicReadingWinsOverScanInTheSameMinute() {
        val result = LibreViewCsv.parse(
            csv(row("08-10-2026 17:47", 1, scan = "6.6"), row("08-10-2026 17:47", 0, historic = "6.4")),
            kaliningrad,
        )
        assertEquals(1, result.readings.size)
        assertFalse(result.readings.single().scan)
        assertEquals(6.4, result.readings.single().mmol, 0.0)
    }

    @Test
    fun unitIsGuessedWhenHeaderHasNoUnits() {
        val text = "Device,Serial Number,Device Timestamp,Record Type,Historic Glucose,Scan Glucose\n" +
            "FreeStyle LibreLink,X,08-10-2026 17:47,0,115,\n" +
            "FreeStyle LibreLink,X,08-10-2026 18:02,0,124,"
        val result = LibreViewCsv.parse(text, kaliningrad)
        assertEquals(GlucoseUnit.MGDL, result.unit)
        assertEquals(listOf(115.0, 124.0), result.readings.map { it.mgDl })
    }

    @Test
    fun windows1251FileIsDecoded() {
        val text = "Устройство;Серийный номер;Отметка времени устройства;Тип записи;Хронология уровня глюкозы ммоль/л;Сканирование\n" +
            "FreeStyle LibreLink;ABCD;08.10.2026 17:47;0;6,4;"
        val bytes = text.toByteArray(Charset.forName("windows-1251"))
        val decoded = LibreViewCsv.decode(bytes)
        assertEquals(text, decoded)
        assertEquals(1, LibreViewCsv.parse(decoded, kaliningrad).readings.size)
    }

    @Test
    fun notACsvGivesNoReadings() {
        val result = LibreViewCsv.parse("<html><body>Войдите в LibreView</body></html>", kaliningrad)
        assertTrue(result.readings.isEmpty())
    }

    @Test
    fun separatorIsDetected() {
        assertEquals(';', LibreViewCsv.detectSeparator("a;b;c\n\"1,5\";2;3"))
        assertEquals(',', LibreViewCsv.detectSeparator("a,b,c\n1,2,3"))
        assertEquals('\t', LibreViewCsv.detectSeparator("a\tb\tc"))
    }
}
